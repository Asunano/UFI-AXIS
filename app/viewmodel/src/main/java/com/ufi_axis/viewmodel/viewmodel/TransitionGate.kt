package com.ufi_axis.viewmodel.viewmodel

import com.ufi_axis_core.util.UiFrameGate

/**
 * 「这次页面转场结束之前，先别把结果写进状态」。
 *
 * ## 为什么需要它（2026-11-03，用户："进数据多的二级页还是卡，比如短信"）
 *
 * 二级页进场的链路是：组合页面 → `LaunchedEffect` 发起请求 → 响应回来 → `_state.update` →
 * 整页重组（列表、卡片、图表全量重建）。而这条链路的**最后一步**恰好落在进场动画
 * （默认 380×1.2 ≈ 456ms）的时间窗里 —— 动画本身很轻，重活是那次整页重组，
 * 于是表现为"动画中顿一下"。
 *
 * ## 为什么是"延后写入"而不是"延后发请求"
 *
 * 用户提的方案是"动画结束再加载数据"。等价，但更慢：延后发请求 = 动画结束后才开始
 * 网络/DB 往返，用户要多等一个 RTT（LAN 上 30~150ms，弱网更久），看到的是"页面铺好了
 * 但一直空着"。而**请求照发、只把结果压到动画之后**，动画结束时数据已经在手上，
 * 下一帧就能铺满 —— 同样的平滑，感知延迟几乎为零。
 *
 * ## 语义边界（必须遵守）
 *
 * 只用于**非关键、可延迟**的数据落地：列表首屏、图表序列、统计读数。
 * 用户操作产生的反馈（点击后的成功/失败、表单校验、进度）**一律不得**走这里 ——
 * 那些是"必须立刻可见"的语义，压到转场之后会读成"点了没反应"。
 *
 * 闸门（[UiFrameGate]）由导航层在转场期间举起：Tab 切页（`UfiPageSwitcherHost`）与
 * 二级页转场（`UfiNavFrameGate`）都算。空闲时本函数直接返回，稳态零开销。
 */
internal suspend fun awaitTransitionIdle() {
    if (UiFrameGate.isBusy) UiFrameGate.awaitIdle()
}
